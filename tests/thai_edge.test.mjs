  //    ยืนยันซ้ำด้วยปี ค.ศ. ตรง ๆ (ไม่ผ่านการแปลง พ.ศ.) กันบั๊กเป็นเรื่องเฉพาะ พ.ศ.
  eq("[บั๊ก] 29/02/2025 (ค.ศ.ตรง ไม่อธิกสุรทิน) → ควรเป็น null", p("29/02/2025"), null);

  // -- ควบคุม (control): วันที่ที่ถูกต้องจริงต้องยังผ่านเหมือนเดิม ไม่ใช่ห้ามทุกอย่าง --
  eq("[ยืนยันถูก] 29 กุมภาพันธ์ 2567 (พ.ศ.2567=ค.ศ.2024 อธิกสุรทินจริง) → ผ่าน", p("29 กุมภาพันธ์ 2567"), { y: 2567, m: 2, d: 29 });
  eq("[ยืนยันถูก] 30 เมษายน 2569 (เม.ย. มี 30 วันพอดี) → ผ่าน", p("30 เมษายน 2569"), { y: 2569, m: 4, d: 30 });
