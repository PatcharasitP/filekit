  // กับตัวย่อทางการ "ม.ค.") — ระบบตอบ null (ปฏิเสธว่าอ่านไม่ออก) ไม่ใช่ตอบวันที่ผิด จึง fail-safe ไม่ใช่บั๊กอันตราย
