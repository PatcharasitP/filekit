/* ตรวจตัวเดาชนิดข้อมูลของคอลัมน์ (สำหรับสร้างโค้ด Power Query)
 *
 * ทำไมต้องมี: เดาผิดแล้วผู้ใช้เสียข้อมูลถาวรโดยไม่รู้ตัว เช่นเลขบัตรประชาชนถูกอ่านเป็นตัวเลข
 * แล้วถูกปัดเป็นค่าประมาณ หรือเบอร์โทรที่ศูนย์นำหน้าหายไป
 * หลักที่ยึด: ไม่มั่นใจเมื่อไหร่ ต้องตกไปเป็น "ข้อความ" เสมอ ห้ามเลือกชนิดที่พบบ่อยที่สุด
 */
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

// โหลดโมดูลจริงโดยแทน i18n ด้วยตัวแทนง่าย ๆ (เทสนี้ไม่ได้ตรวจคำแปล)
const thaiSrc = readFileSync(join(ROOT, "src/thai.js"), "utf8")
  .replace(/^import .*$/gm, 'const tr = (th) => th;');
const thaiUrl = "data:text/javascript;base64," + Buffer.from(thaiSrc).toString("base64");
const src = readFileSync(join(ROOT, "src/pqtypes.js"), "utf8")
  .replace(/^import \{ parseAnyDate, thaiToArabicDigits \} from "\.\/thai\.js";$/m,
           `import { parseAnyDate, thaiToArabicDigits } from "${thaiUrl}";`)
  .replace(/^import \{ tr \} from "\.\/i18n\.js";$/m, "const tr = (th) => th;");
const { classifyCell, guessColumnType } =
  await import("data:text/javascript;base64," + Buffer.from(src).toString("base64"));

let pass = 0;
const fail = [];
const ck = (name, got, want) => {
  const ok = got === want;
  if (ok) pass++;
  else fail.push(`${name}\n      ได้    : ${got}\n      ควรได้ : ${want}`);
  console.log(`  ${ok ? "✅" : "❌"} ${name}`);
};
const col = (vals) => guessColumnType(vals).type;
const conf = (vals) => guessColumnType(vals).confidence;

console.log("\n━━ ① ชนิดพื้นฐานที่ต้องเดาถูก ━━");
ck("ข้อความล้วน", col(["สมชาย", "สมหญิง", "อานันท์"]), "text");
ck("จำนวนเต็ม", col([1001, 1002, 1003]), "int64");
ck("ทศนิยม", col([12500.5, 8500.25]), "number");
ck("จำนวนเต็มปนทศนิยม ต้องเป็นทศนิยม", col([100, 12500.5]), "number");
ck("จริงเท็จแบบอังกฤษ", col(["TRUE", "FALSE", "TRUE"]), "logical");
ck("จริงเท็จแบบไทย", col(["ใช่", "ไม่ใช่", "ใช่"]), "logical");
ck("จริงเท็จแบบ Y/N", col(["Y", "N", "Y"]), "logical");
ck("จริงเท็จที่มาเป็นค่าบูลีนจริง", col([true, false]), "logical");
ck("เปอร์เซ็นต์", col(["87.5%", "72.0%", "95%"]), "percentage");
ck("จำนวนเงินมีหน่วย", col(["1,250.50 บาท", "8,500.00 บาท"]), "currency");
ck("จำนวนเงินมีสัญลักษณ์", col(["฿1,250.50", "฿8,500.00"]), "currency");

console.log("\n━━ ② วันที่และเวลา ━━");
ck("วันที่แบบ ISO", col(["2026-09-01", "2026-01-31"]), "date");
ck("วันที่แบบไทย วัน/เดือน/ปี พ.ศ.", col(["15/01/2569", "28/02/2569"]), "date");
ck("วันที่แบบมีชื่อเดือนไทย", col(["15 มกราคม 2569", "3 มีนาคม 2569"]), "date");
ck("วันที่ที่มาเป็น Date object เที่ยงคืน", col([new Date(2026, 8, 1)]), "date");
ck("วันที่พร้อมเวลา", col([new Date(2026, 8, 1, 8, 30)]), "datetime");
ck("วันที่พร้อมเวลาแบบ ISO", col(["2026-09-01 08:30:00", "2026-09-02 09:15:00"]), "datetime");
ck("วันที่ เวลา โซนเวลา", col(["2026-09-01T08:30:00+07:00", "2026-09-02T09:15:00Z"]), "datetimezone");
ck("เวลา", col(["08:30:00", "09:15:00", "13:00"]), "time");
ck("ช่วงเวลาที่ชั่วโมงเกิน 23", col(["48:30:00", "72:00:00"]), "duration");
ck("ช่วงเวลาที่มีส่วนวันนำหน้า", col(["2.05:30:00", "5.02:00:00"]), "duration");
ck("วันที่ปนวันที่พร้อมเวลา ต้องเป็นวันที่พร้อมเวลา",
   col([new Date(2026, 8, 1), new Date(2026, 8, 2, 10, 0)]), "datetime");

console.log("\n━━ ③ ‼️ ที่หน้าตาเหมือนตัวเลข แต่ต้องเป็นข้อความ ━━");
ck("เลขบัตรประชาชนแบบมีขีด", col(["1-2345-67890-12-3", "1-1037-00123-45-6"]), "text");
ck("เลขบัตรประชาชนแบบไม่มีขีด", col(["1234567890123", "1103700123456"]), "text");
ck("เลขบัตรประชาชนที่มาเป็นตัวเลขแล้ว", col([1234567890123, 1103700123456]), "text");
ck("เบอร์มือถือมีศูนย์นำหน้า", col(["0812345678", "0898765432"]), "text");
ck("เบอร์บ้านมีขีด", col(["02-123-4567", "053-987-654"]), "text");
ck("รหัสสินค้ามีตัวอักษรปน", col(["A01", "B27", "C15"]), "text");
ck("บ้านเลขที่มีทับ", col(["88/2", "199/45"]), "text");
ck("เลขที่หนังสือราชการ", col(["กท 0123/2569", "กค 0456/2569"]), "text");
ck("รหัสไปรษณีย์ที่ขึ้นต้นด้วยศูนย์", col(["01000", "04120"]), "text");

console.log("\n━━ ④ ค่าว่างและค่าที่แปลว่าไม่มีข้อมูล ━━");
ck("ค่าว่างไม่ทำให้ชนิดเพี้ยน", col([1001, null, 1002, ""]), "int64");
ck("ขีดกลางถือว่าไม่มีข้อมูล", col(["100", "-", "200"]), "int64");
ck("N/A ถือว่าไม่มีข้อมูล", col(["2026-09-01", "N/A", "2026-09-02"]), "date");
ck("ไม่ระบุ ถือว่าไม่มีข้อมูล", col(["ใช่", "ไม่ระบุ", "ไม่ใช่"]), "logical");
ck("คอลัมน์ว่างทั้งหมด ตกเป็นข้อความ", col([null, "", "  "]), "text");

console.log("\n━━ ⑤ ‼️ ปนกันแบบครอบกันไม่ได้ ต้องตกเป็นข้อความเสมอ ━━");
ck("ตัวเลขปนข้อความ", col([100, "ยังไม่ระบุ", 200]), "text");
ck("วันที่ปนตัวเลข", col(["2026-09-01", 12345, "2026-09-02"]), "text");
ck("จริงเท็จปนข้อความอื่น", col(["ใช่", "อาจจะ", "ไม่ใช่"]), "text");
ck("เปอร์เซ็นต์ปนตัวเลขเปล่า", col(["87.5%", 0.72]), "text");
// ห้ามเลือก "ชนิดที่พบบ่อยที่สุด" เด็ดขาด แม้ข้างมากจะเป็นตัวเลขก็ตาม
ck("ตัวเลข 9 ตัวปนข้อความ 1 ตัว ก็ยังต้องเป็นข้อความ",
   col([1, 2, 3, 4, 5, 6, 7, 8, 9, "หมายเหตุ"]), "text");

console.log("\n━━ ⑥ ระดับความมั่นใจ ━━");
ck("ข้อมูลชัดเจน มั่นใจสูง", conf(["สมชาย", "สมหญิง"]), "high");
ck("ปนกันจนต้องตกเป็นข้อความ มั่นใจต่ำ", conf([100, "ยังไม่ระบุ"]), "low");
ck("ดูเหมือนรหัส มั่นใจปานกลาง (ให้ผู้ใช้ตัดสินเอง)", conf(["0812345678", "0898765432"]), "medium");
ck("วันที่กำกวมวัน/เดือน มั่นใจปานกลาง", conf(["01/09/2569", "05/03/2569"]), "medium");
ck("วันที่ที่ไม่กำกวม มั่นใจสูง", conf(["15/01/2569", "28/02/2569"]), "high");
ck("ตัวเลขยาวผิดปกติ มั่นใจปานกลาง", conf([123456789, 987654321]), "medium");
ck("คอลัมน์ว่างทั้งหมด มั่นใจต่ำ", conf([null, ""]), "low");

console.log("\n━━ ⑦ เหตุผลต้องบอกผู้ใช้ได้ ━━");
{
  const r = guessColumnType(["0812345678", "0898765432"]);
  ck("มีเหตุผลอธิบายเมื่อไม่มั่นใจ", r.reason.length > 10, true);
  const ok = guessColumnType(["สมชาย", "สมหญิง"]);
  ck("มั่นใจสูงไม่ต้องมีเหตุผลรก", ok.reason, "");
}

console.log("\n━━ ⑧ ค่าเดี่ยว ๆ ━━");
ck("เลขไทยอ่านเป็นตัวเลขได้", classifyCell("๑๒๓").kind, "int64");
ck("ตัวเลขมีคอมมาคั่นหลักพัน", classifyCell("1,234").kind, "int64");
ck("ศูนย์เดี่ยว ๆ ยังเป็นตัวเลข ไม่ใช่รหัส", classifyCell("0").kind, "int64");
ck("ศูนย์นำหน้าที่ยาวกว่าหนึ่งหลัก เป็นรหัส", classifyCell("007").kind, "text");

console.log(`\nผ่าน ${pass} · ตก ${fail.length}`);
fail.forEach((f, i) => console.log(`  ${i + 1}. ${f}`));
process.exit(fail.length ? 1 : 0);
