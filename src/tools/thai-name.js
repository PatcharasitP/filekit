// เรียงจากยาว→สั้น แล้วจับคู่ยาวสุดก่อนเสมอ (กัน "นางสาว" ถูกตัดเหลือแค่ "นาง")
const PREFIX_TABLE = [...new Set(PREFIXES)]
  .sort((a, b) => b.length - a.length)
  .map((p) => ({ p, low: p.toLowerCase(), latinEnd: /[a-zA-Z]$/.test(p) }));

function matchPrefix(s) {
  const low = s.toLowerCase();
  for (const { p, low: pl, latinEnd } of PREFIX_TABLE) {
    if (!low.startsWith(pl)) continue;
    // คำนำหน้าอังกฤษที่ไม่ลงท้ายด้วยจุด (มีแค่ "Miss") ต้องกันชนกลางคำ เช่น "Missy"
    if (latinEnd) {
      const next = s[p.length];
      if (next && /[a-zA-Z]/.test(next)) continue;
    }
    return p;
  }
  return null;
}

// อักขระที่ยอมรับได้ในชื่อ/นามสกุล: ตัวอักษรไทย (พยัญชนะ-สระ-วรรณยุกต์ ไม่รวมเลขไทย) + ตัวอักษรละติน + . ' -
const NAME_CHARS = /^[ก-๎a-zA-Z.'-]+$/;
const HAS_LETTER = /[ก-๎a-zA-Z]/;
const tokenOk = (t) => NAME_CHARS.test(t) && HAS_LETTER.test(t);

export function splitThaiName(raw) {
  let s = String(raw).replace(/\s+/g, " ").trim();
  if (!s) return null;

  // "ว่าที่ ร.ต." / "ว่าที่ร.ต." — ยศมีคำนำหน้าซ้อนอีกชั้น แยกออกมาก่อนแล้วค่อยหายศต่อ
  let waTee = "";
  const wm = s.match(/^ว่าที่\s*/);
  if (wm) { waTee = "ว่าที่"; s = s.slice(wm[0].length); }

  const p = matchPrefix(s);
  const rest = (p ? s.slice(p.length) : s).trimStart();
  const prefixOut = waTee ? (p ? waTee + " " + p : waTee) : (p || "");

  if (!rest) {
    return { ok: false, reason: prefixOut
      ? tr("พบคำนำหน้าแต่ไม่มีชื่อตามหลัง", "Found a title but no name follows it")
      : tr("ไม่พบตัวอักษรที่เป็นชื่อคน", "No name text found") };
  }

  const parts = rest.split(" ").filter(Boolean);
  for (const t of parts) {
    if (!tokenOk(t))
      return { ok: false, reason: tr(`มีตัวเลข/สัญลักษณ์ปน หรือไม่ใช่รูปแบบชื่อคน: "${t}"`,
                                      `Contains digits/symbols, or isn't name text: "${t}"`) };
  }

  const first = parts[0];
  const last = parts.slice(1).join(" ");   // รองรับนามสกุลมีวรรค เช่น "ณ อยุธยา" โดยไม่ต้องมีรายการแยก
  return { ok: true, value: [prefixOut, first, last] };
}

export function mount(tool) {
  return columnTool(tool, {
    accept: ".xlsx,.xls,.csv", expect: ["xlsx", "csv"], expectLabel: tr("ไฟล์ Excel หรือ CSV", "an Excel or CSV file"),
    hint: tr("ไฟล์เดียว .xlsx .xls .csv — คอลัมน์ชื่อเต็ม 1 ช่อง เช่น \"นางสาวสมหญิง ใจดี\"",
             "One .xlsx .xls .csv file — one full-name column, e.g. \"Ms. Jane Doe\""),
    suffix: tr("-แยกชื่อแล้ว", "-name-split"), writeFail: true,
    guessColumn: (h) => /ชื่อ.?สกุล|ชื่อนามสกุล|ชื่อเต็ม|ชื่อ|full\s*name|name/i.test(h),
    labels: { ok: tr("แยกได้", "Split"), bad: tr("แยกไม่ได้", "Could not split") },

    outName: () => [tr("คำนำหน้า", "Title"), tr("ชื่อ", "First name"), tr("นามสกุล", "Surname")],

    convert(v) {
      if (v == null || String(v).trim() === "") return null;
      return splitThaiName(v);
    },

    note: tr("นามสกุลมีวรรค (เช่น ณ อยุธยา) ก็แยกถูก, แถวที่แยกไม่ออกจะบอกเหตุผลไว้ให้",
             "Two-part surnames are handled, rows it cannot split say why"),
  });
}
