/* เทสหน่วยของตัวแยก "ชื่อไทย" กับ "ที่อยู่ไทย" — สองตัวนี้เคยเทสตรง ๆ ไม่ได้เลย
 *
 * ‼️ ที่มา: ทั้ง splitThaiName() กับ parseAddress() เดิมไม่ได้ export ออกมา (ไฟล์ export
 *    แค่ mount(tool)) ทำให้ทดสอบได้แค่ผ่านเบราว์เซอร์ ซึ่งช้าและครอบเคสได้น้อย
 *    (จับได้ตอนไล่เทสเครื่องมือไทยแบบยิงข้อมูลโหด 09/09/2026) · เปิด export เพิ่มแล้ว
 *    จึงยิงเคสโหดเข้าไปตรง ๆ ได้ — งานพวกนี้เอาไปใช้กับข้อมูลจริงของคนอื่น
 *    ถ้าตอบผิดแบบเงียบ ๆ ไม่มีทางรู้เลย จึงต้องมีเทสระดับหน่วยคุมไว้
 *
 * รัน: node tests/thai_parsers.test.mjs
 */
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { splitThaiName } from "../src/tools/thai-name.js";
import { parseAddress, buildGeo } from "../src/tools/thai-address.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
let pass = 0; const fail = [];
const ck = (name, got, want) => {
  const g = JSON.stringify(got), w = JSON.stringify(want);
  if (g === w) { pass++; console.log(`  ✅ ${name}`); }
  else { fail.push(`${name}\n      ได้    : ${g}\n      ควรได้ : ${w}`); console.log(`  ❌ ${name}`); }
};

console.log("\n━━ ชื่อไทย: คำนำหน้า, นามสกุลมีวรรค, ยศทหาร ━━");
const nm = (s) => splitThaiName(s)?.value;
ck("ไม่มีคำนำหน้า", nm("สมชาย ใจดี"), ["", "สมชาย", "ใจดี"]);
ck("คำนำหน้าปกติ", nm("นาย สมชาย ใจดี"), ["นาย", "สมชาย", "ใจดี"]);
ck("คำนำหน้าติดกับชื่อ ไม่เว้นวรรค", nm("นายสมชาย ใจดี"), ["นาย", "สมชาย", "ใจดี"]);
// ยศตำรวจ/ทหารมีจุดคั่นและมีหลายชั้น ต้องไม่ถูกตัดเป็นชื่อ
ck("ยศตำรวจ + นามสกุล ณ อยุธยา", nm("พล.ต.อ. สมชาย ณ อยุธยา"), ["พล.ต.อ.", "สมชาย", "ณ อยุธยา"]);
ck("คำนำหน้าวิชาการซ้อน + นามสกุล 2 คำ", nm("ศ.ดร. สมหญิง ศรี สุวรรณ"), ["ศ.ดร.", "สมหญิง", "ศรี สุวรรณ"]);
ck("ว่าที่ ร.ต. (คำนำหน้า 3 ท่อน)", nm("ว่าที่ ร.ต. สมปอง มีสุข"), ["ว่าที่ ร.ต.", "สมปอง", "มีสุข"]);
ck("มีชื่อเดียว ไม่มีนามสกุล", nm("สมชาย"), ["", "สมชาย", ""]);
ck("ช่องว่างเกินมาหลายที", nm("  นาย   สมชาย    ใจดี  "), ["นาย", "สมชาย", "ใจดี"]);
ck("ค่าว่าง ต้องปฏิเสธ ไม่ใช่เดา", splitThaiName(""), null);
ck("ช่องว่างล้วน ต้องปฏิเสธ", splitThaiName("   "), null);

console.log("\n━━ ที่อยู่ไทย: กรุงเทพใช้แขวง/เขต, เติมรหัสไปรษณีย์ให้, ปฏิเสธเมื่อไม่มั่นใจ ━━");
const geo = buildGeo(JSON.parse(readFileSync(join(ROOT, "vendor/th-address.json"), "utf8")));
const ad = (s) => parseAddress(s, geo);
ck("กรุงเทพฯ ใช้ แขวง/เขต ไม่ใช่ ตำบล/อำเภอ",
   ad("123/4 ถ.สุขุมวิท แขวงคลองเตย เขตคลองเตย กรุงเทพมหานคร 10110").value,
   ["คลองเตย", "คลองเตย", "กรุงเทพมหานคร", "10110"]);
ck("คำย่อ ต./อ./จ. + มีรหัสไปรษณีย์มาแล้ว",
   ad("99 ม.5 ต.บางพลีใหญ่ อ.บางพลี จ.สมุทรปราการ 10540").value,
   ["บางพลีใหญ่", "บางพลี", "สมุทรปราการ", "10540"]);
// "อำเภอเมือง" ลอย ๆ ต้องขยายเป็นชื่อเต็มตามจังหวัด และเติมรหัสไปรษณีย์ให้จากชุดข้อมูล
ck("อำเภอเมือง ต้องขยายเป็นชื่อเต็ม + เติมรหัสไปรษณีย์ให้",
   ad("1 หมู่ 2 ตำบลในเมือง อำเภอเมือง จังหวัดขอนแก่น").value,
   ["ในเมือง", "เมืองขอนแก่น", "ขอนแก่น", "40000"]);
// ‼️ ที่อยู่ที่ไม่มีเบาะแสพอ ต้องบอกว่าแยกไม่ได้ ห้ามเดามั่ว (เจ้าของเว็บย้ำข้อนี้เอง)
ck("ไม่มีคำนำหน้าและหาจังหวัดไม่เจอ ต้องปฏิเสธ", ad("55 ซอย 3 บางรัก").ok, false);
ck("ปฏิเสธแล้วต้องบอกเหตุผลให้คนอ่านเข้าใจ",
   typeof ad("55 ซอย 3 บางรัก").reason === "string" && ad("55 ซอย 3 บางรัก").reason.length > 10, true);
// ชื่อจังหวัดที่เป็นส่วนหนึ่งของชื่ออำเภอ (เมืองพิจิตร ในจังหวัดพิจิตร) ต้องไม่จับสลับกัน
ck("ชื่อจังหวัดซ้อนอยู่ในชื่ออำเภอ ต้องไม่จับสลับ",
   ad("77 ต.เมืองเก่า อ.เมืองพิจิตร พิจิตร 66000").value,
   ["เมืองเก่า", "เมืองพิจิตร", "พิจิตร", "66000"]);
ck("ที่อยู่ที่คลุมเครือแต่แยกได้ ต้องติดธงเตือนไว้ให้คนตรวจ",
   ad("77 ต.เมืองเก่า อ.เมืองพิจิตร พิจิตร 66000").warn, true);
ck("ค่าว่าง ต้องปฏิเสธ", ad("").ok, false);

/* พิสูจน์ว่าเครื่องตรวจเห็นของจริง ไม่ใช่ผ่านเพราะ import พลาดแล้วเงียบ */
console.log("\n━━ 🧪 self-test: ตัวแยกทั้งสองต้องถูก import มาได้จริง ━━");
ck("splitThaiName เป็นฟังก์ชัน", typeof splitThaiName, "function");
ck("parseAddress เป็นฟังก์ชัน", typeof parseAddress, "function");
ck("ชุดข้อมูลที่อยู่โหลดได้ (มีจังหวัดมากกว่า 70)", Object.keys(geo.prov || geo.provinces || {}).length > 70, true);

console.log(`\nผ่าน ${pass}, ตก ${fail.length}`);
for (const [i, x] of fail.entries()) console.log(`  ${i + 1}. ${x}`);
process.exit(fail.length ? 1 : 0);
