/* ตรวจตัวคำนวณระยะห่างสีและการจำลองตาบอดสี
 *
 * ‼️ ทำไมเทสนี้สำคัญ: ตัวเลขจากไฟล์นี้จะถูกเอาไปเตือนผู้ใช้ว่า "ชุดสีนี้คนตาบอดสีแยกไม่ออก"
 *    ถ้าสูตรผิด คำเตือนก็ผิด แล้วคนจะเลือกสีตามคำเตือนที่ผิดไปทั้งองค์กร
 *    สูตร CIEDE2000 มีค่าคงที่เยอะและสลับเครื่องหมายพลาดง่ายมาก ต้องมีตัวจับ
 *
 * ‼️ วิธีตรวจที่เชื่อถือได้โดยไม่ต้องพึ่งตัวเลขที่จำมา
 *    ใช้ "สมบัติที่ต้องจริงเสมอ" เป็นหลัก แล้วเสริมด้วยคู่อ้างอิงมาตรฐานที่สุด 1 คู่
 *      ① ระยะของสีกับตัวเอง = 0 พอดี
 *      ② สลับที่แล้วเท่าเดิม (สูตรนี้สมมาตร)
 *      ③ ต่างกันแค่ความสว่าง 1 หน่วยที่ L=50 ต้องได้ 1.0 พอดี
 *         เพราะที่ L เฉลี่ย = 50 ตัวหาร SL เท่ากับ 1 พอดีตามนิยาม
 *      ④ เทาล้วนสองเฉด ต้องได้ผลเท่ากับผลต่างความสว่างตรง ๆ (ไม่มีเทอมสีมาเกี่ยว)
 *      ⑤ คู่อ้างอิง Sharma ที่ถูกอ้างบ่อยที่สุด (50,0,0) กับ (50,-1,2) = 2.3669
 *
 * รัน: node tests/cvd.test.mjs */
import { deltaE00, deltaEHex, hexToLab, hexToRgb, rgbToLab, simulate, checkPalette, CVD_TYPES } from "../src/cvd.js";

let pass = 0; const fail = [];
const ck = (ok, msg) => { if (ok) { pass++; console.log("  ✅ " + msg); } else { fail.push(msg); console.log("  ❌ " + msg); } };
const near = (a, b, eps = 1e-4) => Math.abs(a - b) <= eps;

/* ── ① ② สมบัติพื้นฐาน ─────────────────────────────────────────────── */
const L1 = { L: 55.2, a: -12.7, b: 33.4 }, L2 = { L: 31.8, a: 44.1, b: -9.6 };
ck(deltaE00(L1, L1) === 0, "① ระยะของสีกับตัวเอง เป็นศูนย์พอดี");
ck(near(deltaE00(L1, L2), deltaE00(L2, L1), 1e-9), "② สลับที่แล้วได้ค่าเท่าเดิม");

/* ── ③ ความสว่างต่างกัน 1 ที่ L=50 ต้องได้ 1.0 เป๊ะ ──────────────────── */
{
  const d = deltaE00({ L: 49.5, a: 0, b: 0 }, { L: 50.5, a: 0, b: 0 });
  ck(near(d, 1.0), `③ ต่างความสว่าง 1 หน่วยที่ L=50 ได้ ${d.toFixed(6)} (ต้องเป็น 1.0)`);
}

/* ── ④ เทาล้วน ไม่มีเทอมสีมาเกี่ยว ──────────────────────────────────── */
{
  const a = { L: 40, a: 0, b: 0 }, b = { L: 60, a: 0, b: 0 };
  const SL = 1 + (0.015 * (50 - 50) ** 2) / Math.sqrt(20 + (50 - 50) ** 2);
  ck(near(deltaE00(a, b), 20 / SL), "④ เทาล้วนสองเฉด ได้ผลเท่ากับผลต่างความสว่างหารด้วย SL");
}

/* ── ⑤ คู่อ้างอิงมาตรฐาน ────────────────────────────────────────────── */
{
  const d = deltaE00({ L: 50, a: 0, b: 0 }, { L: 50, a: -1, b: 2 });
  ck(near(d, 2.3669, 5e-4), `⑤ คู่อ้างอิง Sharma ได้ ${d.toFixed(4)} (ต้องเป็น 2.3669)`);
}

/* ── การแปลงสี ─────────────────────────────────────────────────────── */
{
  const white = rgbToLab(hexToRgb("#ffffff")), black = rgbToLab(hexToRgb("#000000"));
  ck(near(white.L, 100, 0.01) && near(white.a, 0, 0.01), `ขาวต้องได้ L=100 a=b=0 (ได้ L=${white.L.toFixed(2)})`);
  ck(near(black.L, 0, 0.01), `ดำต้องได้ L=0 (ได้ L=${black.L.toFixed(2)})`);
  ck(hexToRgb("#zzz") === null && hexToRgb("") === null, "สีที่อ่านไม่ออก ต้องคืน null ไม่ใช่เดามั่ว");
  ck(Number.isNaN(deltaEHex("#fff", "ไม่ใช่สี")), "เทียบกับค่าที่ไม่ใช่สี ต้องได้ NaN");
}

/* ── จำลองตาบอดสี ───────────────────────────────────────────────────
   ‼️ สมบัติที่ต้องจริง: เทาไม่มีสี จึงต้องแทบไม่เปลี่ยนในทุกภาวะ
      ส่วนแดงกับเขียวต้องเข้าใกล้กันมากขึ้นในภาวะ protanopia/deuteranopia */
for (const t of CVD_TYPES) {
  const d = deltaEHex("#808080", simulate("#808080", t));
  ck(d < 2, `เทากลางแทบไม่เปลี่ยนในภาวะ ${t} (ต่างไป ${d.toFixed(2)})`);
}
{
  const before = deltaEHex("#e00000", "#00a550");
  const after = deltaEHex(simulate("#e00000", "deuteranopia"), simulate("#00a550", "deuteranopia"));
  ck(after < before, `แดงกับเขียวต้องเข้าใกล้กันในภาวะ deuteranopia (${before.toFixed(1)} → ${after.toFixed(1)})`);
}

/* ── ตรวจทั้งชุดสี ─────────────────────────────────────────────────── */
{
  const same = checkPalette(["#3366cc", "#3366cc", "#3366cc"]);
  ck(same.maxSafe === 1 && same.pairs.length > 0, `สีซ้ำกันทั้งชุด ต้องบอกว่าใช้ได้แค่ 1 สี (ได้ ${same.maxSafe})`);
  const two = checkPalette(["#000000", "#ffffff"]);
  ck(two.maxSafe === 2 && two.pairs.length === 0, "ดำกับขาว ต้องแยกออกทุกภาวะ");
  /* ‼️ ข้อสำคัญที่สุด: ชุดสีจริงของธีม TRUE ต้องถูกเตือนว่าเกินเพดาน 5 สี
     ตามที่ PBI_THEME_PLAYBOOK TH3 สรุปไว้ว่า 8 สีแยกครบทุกภาวะเป็นไปไม่ได้ */
  const trueish = checkPalette(["#E4002B", "#1A1A2E", "#0052CC", "#00A550", "#F5A623", "#9B51E0", "#00B8D9", "#FF8B00"]);
  ck(trueish.maxSafe < 8, `ชุด 8 สีต้องถูกเตือนว่าแยกไม่ครบ (ใช้ได้ ${trueish.maxSafe} สีแรก, แย่สุดที่ ${trueish.worst})`);
  ck(checkPalette([]).maxSafe === 0, "ชุดว่าง ต้องไม่พัง");
}

console.log(`\n${fail.length ? "❌" : "✅"} ผ่าน ${pass} ข้อ, ตก ${fail.length} ข้อ`);
process.exit(fail.length ? 1 : 0);
