/* ตรวจตัวไฮไลต์โค้ด: ทาสีถูก และ "คัดลอกแล้วต้องได้ต้นฉบับเป๊ะ"
 *
 * ‼️ ที่มาของเทสนี้คือบั๊กจริงที่หลุดไปกับ v75
 *    paintM รุ่นแรกไล่ replace ทีละรอบ ทาคอมเมนต์ก่อนแล้วค่อยทาสตริง
 *    รอบสองไปเจอ class="cv-cmt" ที่รอบแรกเพิ่งใส่ แล้วนับว่าเป็นสตริงของโค้ด
 *    ได้ <i class=<i class="cv-str">"cv-cmt"</i>> ซึ่ง HTML พัง เบราว์เซอร์กลืน <i class= ทิ้ง
 *    แล้วโชว์ 'cv-cmt">// ...' เป็นตัวหนังสือให้ผู้ใช้เห็นเต็ม ๆ
 *    ไม่โผล่มาก่อนเพราะสเปก Deneb เป็น JSON จึงไม่เคยเดินผ่าน paintM ที่มีคอมเมนต์
 *
 * หลักที่เทสนี้ยึด: ตัวทาสีต้องไม่อ่านสิ่งที่ตัวเองเพิ่งเขียนออกไป
 * วัดด้วยกฎเดียวที่ตรวจได้เสมอ — ถอดแท็ก <i> ออกแล้วคลาย entity ต้องได้ต้นฉบับกลับมาเป๊ะ
 * ถ้าตัวทาสีไปทาทับ markup ของตัวเอง กฎนี้จะพังทันทีโดยไม่ต้องรู้ว่าพังยังไง
 *
 * รัน: node tests/paint.test.mjs */
import { paintCode } from "../src/codeview.js";

let pass = 0; const fail = [];
const ck = (ok, msg) => { if (ok) { pass++; console.log("  ✅ " + msg); } else { fail.push(msg); console.log("  ❌ " + msg); } };

/** จำลอง element.textContent ของเบราว์เซอร์: ถอดแท็ก <i> แล้วคลาย entity */
const asText = (html) => html
  .replace(/<\/?i[^>]*>/g, "")
  .replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");

const CASES = [
  // ── ภาษา M ───────────────────────────────────────────────────────────────
  ["m", 'let\n    // หมายเหตุ "สำคัญ" ตรงนี้\n    x = 1\nin\n    x',
   "คอมเมนต์ M ที่มีเครื่องหมายคำพูดข้างใน (เคสที่ทำให้ v75 พัง)"],
  ["m", 'let\n    // ปกติ\n    s = "ข้อความ"\nin\n    s', "คอมเมนต์ M ธรรมดา"],
  ["m", 'each if [a] = null then "ว่าง" else try [b] otherwise "พัง"', "คำสงวน M หลายตัว"],
  ["m", '"คำว่า let กับ in ที่อยู่ในสตริง ห้ามถูกทาสี"', "คำสงวนในสตริง M"],
  ["m", 'let x = "เขา said ""hi"" แล้วไป" in x', "สตริง M ที่มีคำพูดซ้อน"],
  // ── JSON ────────────────────────────────────────────────────────────────
  ["json", '{"วันที่":"2026-09-11","n":-1.5e3,"ok":true,"ว่าง":null}', "JSON ครบทุกชนิดค่า"],
  ["json", '{"a":"ข้อความที่มี \\" อยู่ข้างใน"}', "JSON ที่มีคำพูด escape"],
  ["json", '{"<b>":"<i>ไม่ใช่แท็กจริง</i>"}', "JSON ที่มีอักขระคล้ายแท็ก HTML"],
  // ── DAX ─────────────────────────────────────────────────────────────────
  ["dax", 'Details = \nIF (\n    ISINSCOPE ( Sales[Order Number] ),\n    "ว่าง"\n)', "DAX มีฟังก์ชัน คอลัมน์ และสตริง"],
  ["dax", "-- หมายเหตุ: ISINSCOPE ( Sales[X] ) ในคอมเมนต์ห้ามถูกทาสี\nVAR x = 1\nRETURN x",
   "คอมเมนต์ DAX แบบขีดสองขีด ที่มีโค้ดอยู่ข้างใน"],
  ["dax", "FORMAT ( 'Sales Order'[Qty], \"#,0\" ) & \" -- ไม่ใช่คอมเมนต์ \"", "ขีดสองขีดที่อยู่ในสตริง ห้ามกลายเป็นคอมเมนต์"],
  ["dax", "VAR a = 5 - 3\nRETURN a", "เครื่องหมายลบตัวเดียว ห้ามถูกอ่านเป็นคอมเมนต์"],
  // ── HTML ────────────────────────────────────────────────────────────────
  ["html", '<table width="640"><tr><td style="padding:8px">ก&amp;ข</td></tr></table>',
   "HTML ตารางพร้อม attribute และ entity"],
  ["html", '<!-- ความเห็น <td> ปลอมในคอมเมนต์ -->\n<td>จริง</td>', "แท็กปลอมในคอมเมนต์ HTML"],
  ["html", '<td>1 &lt; 2 &amp;&amp; 3 &gt; 2</td>', "HTML ที่มี entity เปรียบเทียบ"],
];

for (const [lang, src, label] of CASES) {
  const out = paintCode(src, lang);
  // ① กฎเหล็ก: คัดลอกแล้วต้องได้ต้นฉบับเป๊ะ
  ck(asText(out) === src, `${label} — คัดลอกแล้วได้ต้นฉบับเป๊ะ`);
  // ② markup ของตัวเองต้องไม่โผล่มาเป็นเนื้อความ
  ck(!out.includes("class=<i") && !/cv-(?:cmt|str|kw|key|num|lit)"&gt;/.test(out),
     `${label} — ไม่มี markup ซ้อนทับตัวเอง`);
}

// ③ ต้องทาสีจริง ไม่ใช่คืนข้อความเปล่า (กันเคส "ปลอดภัยเพราะไม่ทำอะไรเลย")
for (const [lang, src, label] of CASES) {
  const n = (paintCode(src, lang).match(/<i class="cv-/g) || []).length;
  ck(n > 0, `${label} — ทาสีจริง ${n} โทเคน`);
}

// ④ ภาษาที่ไม่รู้จัก ต้องยัง escape ให้ปลอดภัย ไม่ปล่อยแท็กดิบทะลุ
const raw = paintCode('<script>alert(1)</script>', "ไม่มีภาษานี้");
ck(!raw.includes("<script"), "ภาษาที่ไม่รู้จักยัง escape ให้ปลอดภัย");
ck(asText(raw) === '<script>alert(1)</script>', "ภาษาที่ไม่รู้จักยังคัดลอกได้ต้นฉบับ");

console.log(`\n${fail.length ? "❌" : "✅"} ผ่าน ${pass} ข้อ, ตก ${fail.length} ข้อ`);
process.exit(fail.length ? 1 : 0);
