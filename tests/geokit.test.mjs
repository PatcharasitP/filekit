console.log("\n⑩ พิสูจน์ว่าเทสชุดนี้แดงเป็น");
{
  // สูตรที่คนพลาดบ่อยที่สุด: วัดระยะแบบระนาบ (Pythagoras) โดยลืมว่าลองจิจูดหดตามละติจูด
  const flat = (la, lo, lan, lon) => Math.hypot(lan - la, lon - lo) * 111.32;
  let worst = 0;
  for (const [, la, lo, , lan, lon, want] of REAL) worst = Math.max(worst, Math.abs(flat(la, lo, lan, lon) - want));
  ck(worst > 0.02, `สูตรระนาบให้ผลต่างจากของจริงถึง ${(worst * 1000).toFixed(0)} เมตร แปลว่าข้อ ② จับความผิดแบบนี้ได้`);
  const badWkt = `LINESTRING (${13.5} ${100.5})`;               // สลับลำดับ
  ck(badWkt !== lineWKT(13.5, 100.5, 13.6, 100.6), "WKT ที่สลับลำดับพิกัด ต่างจากของจริง ข้อ ⑤ จับได้");
}

