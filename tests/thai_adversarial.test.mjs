/* ══════════════════════════════════════════════════════════════════════════
   ③ thai-id — Excel ทำเลขบัตรกลายเป็น float/scientific notation
   สูตรตรวจสอบอ้างอิง: เลขบัตรประชาชนไทย 13 หลัก หลักที่ 13 = (11 - (Σ digit[i]×(13-i) for i=0..11)) mod 11) mod 10
   (สูตรมาตรฐานตามกรมการปกครอง — เป็นสูตรเดียวกับที่ thai.js:checkThaiId13 ใช้ เขียนแยกอิสระที่นี่เพื่อคำนวณ
   เลขบัตรทดสอบเอง ไม่ได้อ้างอิงพฤติกรรมของโค้ดที่จะเทส)
   ══════════════════════════════════════════════════════════════════════════ */
console.log("\n━━ ③ thai-id: Excel float/scientific notation corruption ━━");
{
  function computeCheckDigit(first12) {
    let sum = 0;
    for (let i = 0; i < 12; i++) sum += +first12[i] * (13 - i);
    return (11 - (sum % 11)) % 10;
  }
  const first12 = "110070154123";
  const validId = first12 + computeCheckDigit(first12); // = "1100701541234" คำนวณอิสระด้วยสูตรข้างบน

  // ก. ค่าจาก Excel ที่ยังไม่เสียความละเอียด (13 หลัก < 2^53 เก็บเป็น float ได้แม่นตรง ไม่มีปัดเศษ)
  //    String(Number) ของ JS ไม่ใช้ scientific notation จนกว่าค่าจะ >= 1e21 จึงคืนเลข 13 หลักตรง ๆ
  const asNumber = Number(validId);
  eq("เลขบัตรถูกต้อง จาก Excel เป็น JS number เต็มความละเอียด (1.10123e12 ที่ไม่เสีย precision) → ok:true",
     T.checkThaiId13(asNumber), { ok: true, digits: validId });

  // ข. ค่าที่ Excel แสดงแบบ Scientific (คอลัมน์แคบ/format Scientific) แล้ว export เป็นข้อความ "1.10070E+12"
  //    ความละเอียดหายจริง (เหลือแค่ 6 หลักนัยสำคัญ) — คำตอบที่ถูกต้องคือ "ปฏิเสธ" เพราะกู้เลขจริงคืนไม่ได้
  //    ไม่ใช่ "แปลงแล้วยอมรับเป็นเลขอื่นที่ไม่ตรงของจริง" (นั่นจะอันตรายกว่า)
  const sciText = asNumber.toExponential(5).toUpperCase(); // "1.10070E+12" (Excel scientific-format style)
  const sciResult = T.checkThaiId13(sciText);
  eq(`เลขบัตรกลายเป็น scientific notation "${sciText}" (เสีย precision จริง) → ok:false (ปฏิเสธถูกต้อง ไม่ใช่ยอมรับเลขผิด)`,
     sciResult.ok, false);

  // ค. เลขบัตรขึ้นต้นด้วย 0 (มีจริงในทางทฤษฎี) ถ้า Excel เก็บเป็น "number" (ไม่ใช่ text) เลข 0 นำหน้าจะหายไปเอง
  //    เพราะ Number("0110070154120") → 110070154120 (12 หลัก) — ต้องรายงาน "ผิดจำนวนหลัก" ไม่ใช่เงียบผ่าน
  const idLeadingZero = "0" + first12.slice(0, 11);
  const validIdLZ = idLeadingZero + computeCheckDigit(idLeadingZero);
  const numberLZ = Number(validIdLZ); // Excel ทำแบบนี้จริงถ้าคอลัมน์ format = number/General
  const lzResult = T.checkThaiId13(numberLZ);
  eq(`เลขบัตรขึ้นต้น 0 ที่ Excel ทำเป็น number จนเลข 0 หาย ("${validIdLZ}" → ${numberLZ}) → ok:false มี 12 หลัก`,
     lzResult, { ok: false, reason: "มี 12 หลัก (ต้องมี 13 หลัก)", digits: String(numberLZ) });
}

/* ══════════════════════════════════════════════════════════════════════════
   ④ thai-number — ปัดเศษเปลี่ยนหลัก + ตัวเลขระดับล้านล้าน
   กฎการปัดสตางค์: ปัดเศษสตางค์แบบ "ปัดขึ้นเมื่อถึงครึ่ง" (round-half-up) ที่ตำแหน่งสตางค์ (ทศนิยม 2 ตำแหน่งของบาท)
   คำนวณอิสระ: 0.555 บาท = 55.5 สตางค์ → ปัดขึ้น = 56 สตางค์ · 4.999 บาท = 499.9 สตางค์ → ปัดขึ้น = 500 สตางค์ = 5.00 บาทถ้วน
   กฎอ่านจำนวนล้าน: ภาษาไทยไม่มีคำเฉพาะของ "ล้านล้าน" (trillion) ใช้ "ล้าน" ซ้อน "ล้าน" ตามหลักการจัดกลุ่มเลข 6 หลัก
   ══════════════════════════════════════════════════════════════════════════ */
console.log("\n━━ ④ thai-number: ปัดเศษเปลี่ยนหลัก + ล้านล้าน ━━");
{
  eq("0.555 → ปัดขึ้นเป็น 56 สตางค์ (55.5 ปัดขึ้นตามกฎปัดครึ่งขึ้น)", T.bahtText(0.555), "ห้าสิบหกสตางค์");
  eq("4.999 → ปัดขึ้นข้ามเป็น 5 บาทถ้วน (499.9 สตางค์ ปัดเป็น 500 = 5.00 บาท)", T.bahtText(4.999), "ห้าบาทถ้วน");
  eq("1,000,000,000,000 (หนึ่งล้านล้าน) → \"หนึ่งล้านล้านบาทถ้วน\"", T.bahtText(1000000000000), "หนึ่งล้านล้านบาทถ้วน");
  // 1,234,567,890,123 = กลุ่มบน "1,234,567" (ล้าน) + กลุ่มล่าง "890,123"
  //   1,234,567 อ่านเอง: 1ล้าน 2แสน 3หมื่น 4พัน 5ร้อย 6สิบ 7 = "หนึ่งล้านสองแสนสามหมื่นสี่พันห้าร้อยหกสิบเจ็ด"
  //   890,123   อ่านเอง: 8แสน 9หมื่น (0พันข้าม) 1ร้อย 2สิบ 3  = "แปดแสนเก้าหมื่นหนึ่งร้อยยี่สิบสาม"
  //   รวม: (กลุ่มบน) + "ล้าน" + (กลุ่มล่าง)
  eq("1,234,567,890,123 (คอมโพสิตข้ามล้านล้าน) → อ่านตรงตามกฎจัดกลุ่ม 6 หลัก",
     T.readThaiInteger(1234567890123),
     "หนึ่งล้านสองแสนสามหมื่นสี่พันห้าร้อยหกสิบเจ็ดล้านแปดแสนเก้าหมื่นหนึ่งร้อยยี่สิบสาม");
}

/* ══════════════════════════════════════════════════════════════════════════
   ④½ เพี้ยนซ้อนหลายชั้น — "ซ่อมแล้ว" ต้องแปลว่าซ่อมจริง ไม่ใช่แค่ลอกออกชั้นเดียว
   ไฟล์เก่าที่เวียนกันเปิดหลายโปรแกรมถูกอ่านผิดแล้วบันทึกทับได้หลายรอบ
   ก่อนแก้: แกะรอบเดียวแล้วขึ้นว่าซ่อมแล้ว ทั้งที่ข้อความยังเป็นขยะอยู่ (พบ 09/09/2026)
   ══════════════════════════════════════════════════════════════════════════ */
console.log("\n━━ ④½ เพี้ยนซ้อนหลายชั้น ━━");
{
  // จำลองการบันทึกผิด 1 รอบ: เอาไบต์ UTF-8 ไปอ่านด้วยตาราง 874 แล้วบันทึกเป็น UTF-8 อีกที
  const missave = (s) => new TextDecoder("windows-874").decode(new TextEncoder().encode(s));
  const orig = "ชื่อ,แผนก,ตำแหน่ง\nสมชาย,บัญชี,ผู้จัดการ\nสมหญิง,การตลาด,หัวหน้าฝ่าย\n";
  for (const n of [1, 2, 3]) {
    let t = orig;
    for (let i = 0; i < n; i++) t = missave(t);
    const u8 = new TextEncoder().encode(t);
    eq(`เพี้ยนซ้อน ${n} ชั้น → ซ่อมกลับได้ตรงต้นฉบับทุกตัวอักษร`, T.smartDecode(u8).text, orig);
    eq(`เพี้ยนซ้อน ${n} ชั้น → รายงานจำนวนชั้นตรงความจริง`, T.analyzeBytes(u8).best.passes, n);
  }
  // ‼️ ด่านกันพัง: ไทยแท้ที่มีรูป "เ + ธ/น" ห้ามถูกไล่แกะซ้ำจนเนื้อหาเสีย
  for (const good of ["เธอเป็นคนดีเสมอมา", "เนื่องจากเธอไม่มาเรียนเธอจึงสอบตก", "ผลิตภัณฑ์ธรรมชาติ"]) {
    eq(`ไทยแท้ "${good.slice(0, 12)}" ไม่ถูกแตะแม้แต่ตัวเดียว`,
       T.smartDecode(new TextEncoder().encode(good)).text, good);
  }
  // เพดานรอบต้องมีจริง กันวนไม่จบ
  eq("มีเพดานจำนวนรอบการแกะ (กันวนไม่จบ)", typeof T.MAX_UNDO_PASSES === "number" && T.MAX_UNDO_PASSES > 0, true);
}

